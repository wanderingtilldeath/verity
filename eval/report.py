"""python -m eval.report: regenerate docs/results.md from the saved result files (never hand-edit)."""

from __future__ import annotations

import json
import re
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"
BENCH = ROOT / "bench" / "results"
OUT = ROOT / "docs" / "results.md"

SUMMARY_NAME = re.compile(
    r"summary_(?P<ep>\w+?)_(?P<label>[\d.]+[kM])_(?P<rest>.+)_r(?P<rep>\d+)\.json$"
)


def read_text(path: Path, fallback: str) -> str:
    return path.read_text().strip() if path.exists() else fallback


def trend(summary: dict, metric: str) -> dict | None:
    """Prefer the phase=measure sub-metric; fall back to the plain metric (plagiarism script)."""
    m = summary["metrics"]
    return m.get(f"{metric}{{phase:measure}}") or m.get(metric)


def median_of(runs: list[dict], key: str) -> float:
    return statistics.median(r[key] for r in runs if r[key] is not None)


def bench_tables() -> str:
    cells: dict[tuple, list[dict]] = defaultdict(list)
    for f in sorted(BENCH.glob("summary_*.json")):
        m = SUMMARY_NAME.match(f.name)
        if not m:
            continue
        s = json.loads(f.read_text())
        d = trend(s, "http_req_duration")
        reqs = trend(s, "http_reqs")
        if not d:
            continue
        cells[(m["ep"], m["label"], m["rest"])].append(
            {"p50": d["med"], "p95": d["p(95)"], "p99": d["p(99)"], "rps": (reqs or {}).get("rate")}
        )
    if not cells:
        return "_No benchmark results yet. Run `make bench`._"
    rows = [
        "| endpoint | corpus | cell | p50 ms | p95 ms | p99 ms | req/s | runs (p95 min-max) |",
        "|---|---|---|---:|---:|---:|---:|---|",
    ]
    for (ep, label, rest), runs in sorted(cells.items()):
        p95s = [r["p95"] for r in runs]
        rows.append(
            f"| {ep} | {label} | {rest} | {median_of(runs, 'p50'):.1f} | "
            f"{median_of(runs, 'p95'):.1f} | {median_of(runs, 'p99'):.1f} | "
            f"{median_of(runs, 'rps'):.1f} | {len(runs)} ({min(p95s):.1f}-{max(p95s):.1f}) |"
        )
    return "\n".join(rows)


def ingest_table() -> str:
    rows = [
        "| stage | docs | docs/s end-to-end | docs/s ES only | index size | dead letters | 429 retries |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    found = False
    for f in sorted(RESULTS.glob("ingest_*.json")):
        runs = json.loads(f.read_text())
        last = runs[-1]
        found = True
        rows.append(
            f"| {last['stage']} | {last['index']['docs']:,} | {last['docs_per_sec_end_to_end']} | "
            f"{last['docs_per_sec_es_only']} | {last['index']['size_bytes'] / 1e9:.2f} GB | "
            f"{last['dead_letter']} | {last['retries_429']} |"
        )
    return "\n".join(rows) if found else "_No ingest results yet._"


def main() -> None:
    parts = [
        "# Results (generated by `python -m eval.report`; do not edit by hand)",
        "",
        "## Ingestion",
        ingest_table(),
        "",
        "## Plagiarism detection",
        read_text(RESULTS / "plagiarism" / "summary.md", "_Run `make eval-plagiarism`._"),
        "",
        "![PR curves](../eval/results/plagiarism/pr_curves.png)",
        "",
        "## Relevance (known-item search from redirects)",
    ]
    for stage in ("A", "B"):
        parts += [
            read_text(
                RESULTS / "relevance" / f"summary_{stage}.md", f"_Stage {stage}: not run yet._"
            ),
            "",
        ]
    parts += ["## Latency (laptop, single node; k6 shares the machine)", bench_tables(), ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(parts))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
